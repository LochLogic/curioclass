r"""The build board: where every tool is in the pipeline, worked out from its files so it never drifts.

    python scripts/board.py              write docs/BUILD-BOARD.md and print the totals
    python scripts/board.py --wave 1     print one wave's rows

Stages, in order (docs/BUILD-PLAN.md):
  concept   only the catalog line
  spec      tools/<id>/spec.md (spec agent, docs/agents/SPEC.md)
  built     tool.draft.json and src.html (build agent, docs/agents/BUILD.md)
  verified  verify.md whose first line says PASS (verify agent, docs/agents/VERIFY.md)
  art       every asset in art/prompts.json has its .webp
  voice     every line in voice/lines.json has its recording (or the tool has no voice)
  live      tool.json (on the site)
The Plan column says whether tools/<id>/plan.md exists (docs/LESSON-PLANS.md). It doesn't hold back the stage.
Waves come from data/waves.csv (tool_id,wave). Review state lives on the Review Desk, not here.
"""
import csv, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / 'tools'
sys.path.insert(0, str(ROOT / 'scripts'))
from voice import clip_name  # noqa: E402


def art(f):
    p = f / 'art' / 'prompts.json'
    if not p.exists():
        return 0, 0
    names = [a['name'] for a in json.loads(p.read_text(encoding='utf-8'))['assets']]
    return sum((f / 'art' / f'{n}.webp').exists() for n in names), len(names)


def voice(f):
    p = f / 'voice' / 'lines.json'
    if not p.exists():
        return 0, 0
    spec = json.loads(p.read_text(encoding='utf-8'))
    lines = {*spec.get('lines', []), *(t for g in spec.get('groups', []) for t in g)}
    return sum((f / 'voice' / clip_name(t)).exists() for t in lines), len(lines)


def row(tid):
    f = TOOLS / tid
    a, an = art(f); v, vn = voice(f)
    verify = f / 'verify.md'
    verdict = verify.read_text(encoding='utf-8').split('\n', 1)[0].upper() if verify.exists() else ''
    if (f / 'tool.json').exists():
        st = 'live'
    elif (f / 'tool.draft.json').exists():
        st = 'voice' if 'PASS' in verdict and a == an and v == vn and vn else 'art' if 'PASS' in verdict and a == an else 'verified' if 'PASS' in verdict else 'built'
    elif (f / 'spec.md').exists():
        st = 'spec'
    else:
        st = 'concept'
    return {'stage': st, 'art': f'{a}/{an}' if an else '-', 'voice': f'{v}/{vn}' if vn else '-',
            'verify': 'PASS' if 'PASS' in verdict else ('FIX' if verdict else ''), 'plan': 'yes' if (f / 'plan.md').exists() else ''}


ORDER = ['concept', 'spec', 'built', 'verified', 'art', 'voice', 'live']


def main():
    rows = list(csv.DictReader(open(ROOT / 'data' / 'tools-concepts.csv', encoding='utf-8')))
    waves = {}
    wf = ROOT / 'data' / 'waves.csv'
    if wf.exists():
        waves = {r['tool_id']: r['wave'] for r in csv.DictReader(open(wf, encoding='utf-8'))}
    for r in rows:
        r.update(row(r['tool_id'])); r['wave'] = waves.get(r['tool_id'], '')
    if '--wave' in sys.argv:
        w = sys.argv[sys.argv.index('--wave') + 1]
        for r in rows:
            if r['wave'] == w:
                print(f"{r['tool_id']:34} {r['stage']:9} verify {r['verify'] or '-':4} plan {r['plan'] or '-':3} art {r['art']:6} voice {r['voice']}")
        return
    tot = {s: sum(r['stage'] == s for r in rows) for s in ORDER}
    out = ['# Build board', '', 'Generated by `python scripts/board.py` from the files in tools/. Do not edit by hand.', '',
           '| ' + ' | '.join(ORDER) + ' |', '|' + '---|' * len(ORDER), '| ' + ' | '.join(str(tot[s]) for s in ORDER) + ' |', '']
    for w in sorted({r['wave'] for r in rows if r['wave']}, key=lambda x: (len(x), x)):
        out += [f'## Wave {w}', '', '| Tool | Grade | Subject | Format | Family | Stage | Verify | Plan | Art | Voice |', '|---|---|---|---|---|---|---|---|---|---|']
        for r in [r for r in rows if r['wave'] == w]:
            out.append(f"| {r['title']} | {r['grade']} | {r['subject']} | {r['format']} | {r['family'] or ''} | {r['stage']} | {r['verify']} | {r['plan']} | {r['art']} | {r['voice']} |")
        out.append('')
    (ROOT / 'docs' / 'BUILD-BOARD.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('  '.join(f'{s} {tot[s]}' for s in ORDER))


if __name__ == '__main__':
    main()
