// Write docs/agents/GEN-OPTIONS.md: every Worksheet Generator's settings and values, read from the generator files.
//   node scripts/gen_options.mjs
// A generator-backed concept row (data/closet/worksheets/generated.csv) and scripts/gen_links.py use these ids and
// values, so regenerate the file whenever a generator gains or changes a setting. Options that depend on an earlier
// select are listed once per value of that select, where they differ from the defaults' list. The vocabulary and
// puzzle generators read the Word Wall list from dist/ (build with --closet first); their module lists are summarized.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const reg = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/closet/generators.json'), 'utf8'));
const ctx = vm.createContext({ console, Math, JSON, Set, Map, Array, Object, String, Number, Date });
const load = f => vm.runInContext(fs.readFileSync(f, 'utf8'), ctx, { filename: f });
load(path.join(ROOT, 'site/assets/gen/engine.js'));
const Gen = ctx.Gen;
const dist = process.env.CURIO_DIST || path.join(ROOT, 'dist');
const out = ['# Worksheet Generators: every setting and its values', '',
  'Generated by `node scripts/gen_options.mjs` from site/assets/gen/*.js. A generator-backed concept row (data/closet/worksheets/generated.csv) uses these ids and values in its query string; so does scripts/gen_links.py.', ''];
const list = opts => opts.map(([v, l]) => `${v} (${l})`).join(', ');
const MODULE_FIELDS = new Set(['mod']);

for (const g of reg.generators) {
  const pre = path.join(ROOT, 'site/assets/gen', g.id + '-data.js');
  if (fs.existsSync(pre)) load(pre);
  load(path.join(ROOT, 'site/assets/gen', g.id + '.js'));
  const def = Gen.defs[g.id];
  let d = null;
  if (def.data) {
    const f = path.join(dist, 'closet/worksheets/make', def.data + '.json');
    if (fs.existsSync(f)) d = JSON.parse(fs.readFileSync(f, 'utf8'));
  }
  out.push(`## ${g.id}: ${g.title} (grades ${g.grades})`, '', g.blurb, '');
  const base = Gen.values(def, {}, d);
  for (const f of def.fields) {
    const only = f.show ? ', only in some modes' : '';
    if (f.type === 'select') {
      if (MODULE_FIELDS.has(f.id)) { const n = Gen.opts(f, base, d).length; out.push(`- **${f.id}** (${f.label}${only}; default "${f.def ?? ''}"): a module id from data/modules.csv that has Word Wall words (${n} listed for the default subject and band; see dist/closet/worksheets/make/words.json)`); continue; }
      out.push(`- **${f.id}** (${f.label}${only}; default "${f.def ?? ''}"): ${list(Gen.opts(f, base, d))}`);
      if (typeof f.options === 'function') {   // list the options under each value of every earlier select that changes them
        const baseList = JSON.stringify(Gen.opts(f, base, d));
        for (const e of def.fields) {
          if (e === f) break;
          if (e.type !== 'select' || MODULE_FIELDS.has(e.id)) continue;
          for (const [val] of Gen.opts(e, base, d)) {
            const v = Gen.values(def, { ...base, [e.id]: val }, d);
            const o = Gen.opts(f, v, d);
            if (JSON.stringify(o) !== baseList) out.push(`  - when ${e.id}=${val}: ${list(o)}`);
          }
        }
      }
    } else if (f.type === 'check') out.push(`- **${f.id}** (${f.label}${only}; default ${f.def ? 'on' : 'off'}): 1 (on) or 0 (off)`);
    else if (f.type === 'number') out.push(`- **${f.id}** (${f.label}${only}; default "${f.def ?? ''}"): a number${f.min != null ? ` from ${f.min}` : ''}${f.max != null ? ` to ${f.max}` : ''}`);
    else out.push(`- **${f.id}** (${f.label}${only}; default "${f.def ?? ''}"): free text (240 chars)`);
  }
  out.push('');
}
fs.writeFileSync(path.join(ROOT, 'docs/agents/GEN-OPTIONS.md'), out.join('\n'));
console.log(`docs/agents/GEN-OPTIONS.md: ${reg.generators.length} generators`);
