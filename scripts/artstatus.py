"""Art status for every tool: what each tool needs, what is drawn, placed and checked.

    python scripts/artstatus.py                  table for every tool with art/prompts.json, and docs/ART-STATUS.md
    python scripts/artstatus.py <tool-id>        one tool, asset by asset
    python scripts/artstatus.py <tool-id> --ok name [name ...]          mark checked and good
    python scripts/artstatus.py <tool-id> --redo name:"reason" [...]    mark for a redraw, with the reason

States, from prompts.json and the files on disk:
  needed     in prompts.json, nothing drawn yet
  drawn      candidates in art/raw/, none picked
  placed     art/<name>.webp exists, review "pending" (localart.py --pick sets this)
  ok         checked and good (review "ok"), or the tool is live and was approved before tracking began
  redo       review starts with "redo: ..." (the reason says what is wrong)
  gemini     a person ("people": true): drawn by Gemini with a review, never by a local or Cloudflare model
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATES = ['needed', 'drawn', 'placed', 'redo', 'ok']


def state(tool, a):
    art = ROOT / 'tools' / tool / 'art'
    review = a.get('review', '')
    if review.startswith('redo'):
        return 'redo'
    if (art / f"{a['name']}.webp").exists():
        live = (ROOT / 'tools' / tool / 'tool.json').exists()
        return 'ok' if review == 'ok' or (not review and live) else 'placed'
    if a.get('people'):
        return 'gemini'
    return 'drawn' if list((art / 'raw').glob(f"{a['name']}.c*.png")) else 'needed'


def load(tool):
    f = ROOT / 'tools' / tool / 'art' / 'prompts.json'
    return f, json.loads(f.read_text(encoding='utf-8'))


def main():
    args = sys.argv[1:]
    if len(args) >= 2 and args[1] in ('--ok', '--redo'):
        f, spec = load(args[0])
        by = {a['name']: a for a in spec['assets']}
        for item in args[2:]:
            name, _, why = item.partition(':')
            if name not in by:
                sys.exit(f'no asset {name!r} in {args[0]}')
            by[name]['review'] = 'ok' if args[1] == '--ok' else f'redo: {why or "needs a redraw"}'
        f.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
        args = args[:1]
    tools = args or sorted(p.parent.parent.name for p in (ROOT / 'tools').glob('*/art/prompts.json'))
    rows, lines = [], []
    for t in tools:
        _, spec = load(t)
        sts = [(a, state(t, a)) for a in spec['assets']]
        count = {s: sum(1 for _, x in sts if x == s) for s in STATES + ['gemini']}
        draft = (ROOT / 'tools' / t / 'tool.draft.json').exists()
        rows.append((t, 'draft' if draft else 'live', len(sts), count))
        if args:
            for a, s in sts:
                print(f"  {s:7} {a['name']:16} {a.get('source', '')}  {a.get('review', '') if s == 'redo' else ''}")
    head = f"| Tool | | Needed | Drawn | Placed | Redo | OK | Gemini (people) | Total |\n|---|---|---|---|---|---|---|---|---|"
    body = [f"| {t} | {k} | {c['needed']} | {c['drawn']} | {c['placed']} | {c['redo']} | {c['ok']} | {c['gemini']} | {n} |" for t, k, n, c in rows]
    tot = {s: sum(c[s] for *_, c in rows) for s in STATES + ['gemini']}
    body.append(f"| **All** | | {tot['needed']} | {tot['drawn']} | {tot['placed']} | {tot['redo']} | {tot['ok']} | {tot['gemini']} | {sum(r[2] for r in rows)} |")
    print(head); print('\n'.join(body))
    if not args:
        redo = [f"- {t}/{a['name']}: {a['review'][6:]}" for t in tools for a in load(t)[1]['assets'] if a.get('review', '').startswith('redo')]
        (ROOT / 'docs' / 'ART-STATUS.md').write_text(
            '# Art status\n\nGenerated by `python scripts/artstatus.py`; do not edit by hand. States are explained at the top of that script.\n\n'
            + head + '\n' + '\n'.join(body) + '\n' + ('\n## Redraws\n\n' + '\n'.join(redo) + '\n' if redo else ''), encoding='utf-8')


if __name__ == '__main__':
    main()
