r"""One Codex lane per subject: the course-run queue (docs/COURSE-RUN.md stages 5 and 6), job by job, on main.

    python -X utf8 scripts/codex_lane.py run <subject>          run the lane until it ends, waits for the lead, or STOP
    python -X utf8 scripts/codex_lane.py status [<subject>]     done, next and any wait, per lane
    python -X utf8 scripts/codex_lane.py done <subject> <key>   the lead marks a waiting step done (a retool stop, ...)
    python -X utf8 scripts/codex_lane.py lead-commit "<message>" <path> ...   the lead's own commit, under the lanes' lock

Cory, 2026-11-25: Codex resumes the core days, one terminal per subject, so trouble or a restart in one subject never
touches another. Each lane is its own process; it climbs its subject's ladder (LANES) grade by grade. A course's queue
is generated by scripts/coursegen.py from the current kit when the course starts, so a retool between grades reaches
the next grade. Every job kind of the queue runs: section plans, plan reads, the plan fix, plan data, key reads, days
(each after its ledger gate), check days, the grade sample reads and the cleanup, and for ELA the text jobs. Nothing is
skipped.

The runner is the lead's hands for the mechanical steps (AGENTS.md "Who commits"): it builds the section skeletons,
merges ELA text rows, runs each GATE line's ledger gate before its day job, re-runs `scripts/gate.py --course` after
every job and hands the new failing lines back to the same Codex session once, then commits and pushes only that job's
files (the course's docs/courses/<course>/ and data/plans/<course>/ paths, its docs/reviews/ reports, and the shared
defects and ELA text tables), under one lock shared with every lane and the lead (lead-commit). A job never runs git.

The lane WAITS for the lead (its state folder holds WAITING, saying why) at: a retool stop (every grade close: the
lead's steps in kit/retool-stop.txt), a closed ledger gate, three failed jobs in a row, or a grade whose new gate
failures pile up (more than 10 plus one per day written). It polls every 5 minutes and goes on when the lead runs
`done <subject> <key>` (or deletes WAITING after fixing the cause). A usage limit pauses the lane 30 minutes and the
same job runs again. build/lanes/STOP ends every lane gently; build/lanes/<subject>/STOP ends one. build/lanes/<subject>/ONLY (job kinds, e.g. "DATA KEY") runs just those kinds and leaves the rest queued.

Courses that hold an earlier Codex draft (DRAFTED, unread draft 1 written to an older kit, later.csv L105) run the same
full queue: each make job is told that its files may already exist and is to bring them to the current kit, keeping
what meets it and rewriting what does not.

State (git-ignored), build/lanes/<subject>/: run.log, done.txt, usage.csv, WAITING, <course>/ (queue) and jobs/
(each Codex session's events and last message).
"""
