def now():
    return dt.datetime.now().strftime('%Y-%m-%d %H:%M:%S')


class Lane:
    def __init__(self, subj):
        if subj not in LANES:
            sys.exit('no lane %r (lanes: %s)' % (subj, ', '.join(LANES)))
        self.subj = subj
        self.dir = LANES_DIR / subj
        self.dir.mkdir(parents=True, exist_ok=True)
        self.pause_until = 0.0

    # ------------------------------------------------------------ state
    def log(self, line):
        with open(self.dir / 'run.log', 'a', encoding='utf-8') as f:
            f.write('%s %s\n' % (now(), line))
        print(now(), line, flush=True)

    def done(self):
        p = self.dir / 'done.txt'
        return set(p.read_text(encoding='utf-8').split()) if p.exists() else set()

    def mark(self, key):
        with open(self.dir / 'done.txt', 'a', encoding='utf-8') as f:
            f.write(key + '\n')

    def stopped(self):
        return (LANES_DIR / 'STOP').exists() or (self.dir / 'STOP').exists()

    def wait_for_lead(self, key, why):
        """Write WAITING and poll until the lead marks the key done or removes WAITING. False when stopped."""
        w = self.dir / 'WAITING'
        w.write_text('%s\nkey: %s\n%s\nWhen done: python -X utf8 scripts/codex_lane.py done %s %s\n'
                     % (now(), key, why, self.subj, key), encoding='utf-8')
        self.log('WAITING for the lead at %s: %s' % (key, why.splitlines()[0]))
        while True:
            if self.stopped():
                return False
            if key in self.done() or not w.exists():
                if w.exists():
                    w.unlink()
                self.log('lead cleared %s; lane goes on' % key)
                return True
            time.sleep(POLL)

    # ------------------------------------------------------------ helpers
    def py(self, *args, timeout=1800):
        r = subprocess.run([sys.executable, '-X', 'utf8', *args], cwd=ROOT, capture_output=True, text=True,
                           encoding='utf-8', errors='replace', timeout=timeout)
        return r.returncode, (r.stdout or '') + (r.stderr or '')

    def gate(self, course):
        code, out = self.py('scripts/gate.py', '--course', course)
        m = re.search(r'(\d+) failing finding', out)
        new = [ln for ln in out.splitlines() if ln.startswith('  FAIL-NEW')]
        if m and int(m.group(1)) > len(new):
            new += ['(more)'] * (int(m.group(1)) - len(new))
        return code, out, new

    def queue(self, course):
        out = self.dir / course
        q = out / 'queue.txt'
        if not q.exists():
            args = ['scripts/coursegen.py', self.subj, course, '--out', str(out)]
            if self.subj == 'ela':
                args.append('--texts')
            code, text = self.py(*args)
            if code or not q.exists():
                return None, text
            self.log('queue for %s generated: %s' % (course, text.strip().splitlines()[-1][:200]))
        steps, gate = [], None
        for line in q.read_text(encoding='utf-8').splitlines():
            if line.startswith('#') or '|' not in line:
                continue
            num, kind, c, detail, f = [x.strip() for x in line.split('|', 4)]
            if kind == 'kind':
                continue
            if kind == 'GATE':
                gate = f
                continue
            steps.append(dict(num=num, kind=kind, course=c, detail=detail, file=f,
                              gate=gate if kind in ('DAY', 'CHECKS') else None))
            gate = None
        return steps, ''

    # ------------------------------------------------------------ git (the lead's step, done here)
    def commit(self, course, msg, before):
        allowed = ('docs/courses/%s/' % course, 'data/plans/%s/' % course, 'courses/%s/' % course)   # courses/: ELA texts
        with gitlock():
            while turn_held():
                time.sleep(60)
            paths, outside = [], []
            for p, st in porcelain():
                if p.startswith(allowed) or p in SHARED_OK or (self.subj == 'ela' and p == 'data/plans/ela-texts.csv') \
                        or (p.startswith('docs/reviews/') and course in p):
                    paths.append(p)
                elif p not in before and not p.startswith('build/'):
                    outside.append(p)
            if outside:
                self.log('note: files outside %s changed during the job (not committed by this lane): %s'
                         % (course, ', '.join(outside[:12])))
            if not paths:
                return ''
            git('add', '-A', '--', *paths)
            code, out = git('commit', '-q', '-m', 'Codex lane (%s): %s\n\nRun by scripts/codex_lane.py; the gate was re-run '
                            'after the job.\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>' % (self.subj, msg),
                            '--', *paths)
            if code:
                self.log('commit failed: %s' % out.strip()[:300])
                return ''
            push(self.log)
            return git('rev-parse', '--short', 'HEAD')[1].strip()

    # ------------------------------------------------------------ one Codex job
    def codex(self, step, prompt, extra=()):
        """One Codex job; extra holds added exec options, such as ('-c', 'model="gpt-6.2-sol"', '-c',
        'model_reasoning_effort="high"') from scripts/section_run.py (they hold for the resume too)."""
        extra = list(extra)
        stem = self.dir / 'jobs' / ('%s-%s-%s' % (step['course'], step['num'], step['kind'].lower()))
        stem.parent.mkdir(parents=True, exist_ok=True)
        job = dict(thread=None, usage=[0, 0, 0, 0], limit=False, last='', t0=time.time())

        def session(args, text, suffix):
            events, last = Path('%s%s.jsonl' % (stem, suffix)), Path('%s%s-last.md' % (stem, suffix))
            if last.exists():
                last.unlink()
            with open(events, 'w', encoding='utf-8') as out:
                p = subprocess.Popen([codex_exe(), *args, '--json', '-o', str(last), '-'], cwd=ROOT,
                                     stdin=subprocess.PIPE, stdout=out, stderr=subprocess.STDOUT, text=True,
                                     encoding='utf-8', creationflags=getattr(subprocess, 'CREATE_NEW_PROCESS_GROUP', 0))
                p.stdin.write(text)
                p.stdin.close()
                seen, grew, stalled = 0, time.time(), False
                while p.poll() is None:
                    time.sleep(15)
                    try:
                        size = events.stat().st_size
                    except OSError:
                        size = seen
                    if size != seen:
                        seen, grew = size, time.time()
                    if time.time() - grew > STALL or time.time() - job['t0'] > TIMEBOX:
                        stalled = True
                        subprocess.run(['taskkill', '/T', '/F', '/PID', str(p.pid)], capture_output=True)
                        break
            for line in events.read_text(encoding='utf-8', errors='replace').splitlines():
                try:
                    ev = json.loads(line)
                except ValueError:
                    ev = {}
                t = ev.get('type')
                if t == 'thread.started' and not job['thread']:
                    job['thread'] = ev.get('thread_id')
                if t == 'turn.completed':
                    u = ev.get('usage') or {}
                    for i, k in enumerate(('input_tokens', 'cached_input_tokens', 'output_tokens',
                                           'reasoning_output_tokens')):
                        job['usage'][i] += int(u.get(k) or 0)
                if (t in ('turn.failed', 'error') or 'error' in line[:60].lower()) and \
                        any(w in line.lower() for w in LIMIT_WORDS):
                    job['limit'] = True
            job['last'] = last.read_text(encoding='utf-8', errors='replace') if last.exists() else ''
            return stalled

        def resume(text, suffix):
            job['t0'] = time.time()
            return session(['exec', 'resume', '-c', 'sandbox_mode="workspace-write"', '-c', 'tools.web_search=true',
                            *extra, job['thread']], text, suffix)

        stalled = session(['exec', '-s', 'workspace-write', '-C', str(ROOT), '-c', 'tools.web_search=true',
                           '--color', 'never', *extra], prompt, '')
        if not job['limit'] and (stalled or not job['last'].strip()) and job['thread']:
            self.log('%s: %s; resuming once' % (step['num'], 'silent 20 minutes' if stalled else 'no last message'))
            resume(HUNG if stalled else CARRY, '-resume')
        job['resume'] = resume
        return job

    def usage_row(self, step, result, t0, job, new):
        p = self.dir / 'usage.csv'
        fresh = not p.exists()
        with open(p, 'a', encoding='utf-8', newline='') as f:
            w = csv.writer(f)
            if fresh:
                w.writerow(['ended', 'course', 'job', 'kind', 'detail', 'result', 'minutes', 'tokens_in', 'cached_in',
                            'tokens_out', 'reasoning_out', 'new_gate_lines'])
            u = job['usage'] if job else [0, 0, 0, 0]
            w.writerow([now(), step['course'], step['num'], step['kind'], step['detail'], result,
                        round((time.time() - t0) / 60, 1), *u, new])

    # ------------------------------------------------------------ lead steps the runner can do
    def lead_step(self, step):
        d = step['detail']
        if d.startswith('BUILD section skeletons'):
            m = re.search(r'python -X utf8 (scripts/\S+\.py)((?: [\w-]+)*)', d)
            code, out = self.py(m.group(1), *m.group(2).split()) if m else (1, 'no command in the line')
            self.log('%s skeletons: exit %d %s' % (step['course'], code, out.strip().splitlines()[-1:] if out.strip() else ''))
            return code == 0, out
        if d.startswith('MERGE texts-out/'):
            n = merge_texts(step['course'], '-new.csv' in d)
            code, out = self.py('scripts/section_skeleton.py', step['course'], 'all')
            self.log('%s text merge: %d rows; skeletons rebuilt (exit %d)' % (step['course'], n, code))
            return True, ''
        code, out, new = self.gate(step['course'])
        self.log('%s lead gate check (%s): exit %d, %d new line(s)' % (step['course'], d[:60], code, len(new)))
        return True, out

    def only(self):
        """Job kinds (and any course names) in build/lanes/<subject>/ONLY (space or line separated), or None to run every kind. A skipped
        step is not marked done, so it runs once ONLY is removed (Cory 2026-11-26: math kindergarten sections only)."""
        f = self.dir / 'ONLY'
        return set(f.read_text(encoding='utf-8').split()) if f.exists() else None

    # ------------------------------------------------------------ the lane
    def run(self):
        keep_awake(True)
        self.log('lane starts: %s' % ' > '.join(LANES[self.subj]))
        fails = 0
        for course in LANES[self.subj]:
            only = self.only() or set()
            if any('-' in w for w in only) and course not in only:   # ONLY may also name the courses to run
                self.log('ONLY names no %s; skipped' % course)
                continue
            steps, err = self.queue(course)
            if steps is None:
                if not self.wait_for_lead('%s:queue' % course, 'coursegen could not make the queue for %s:\n%s'
                                          % (course, err.strip()[-2000:])):
                    return
                steps, err = self.queue(course)
                if steps is None:
                    self.log('still no queue for %s; lane ends' % course)
                    return
            grade_new = grade_days = 0
            for step in steps:
                key = '%s:%s' % (course, step['num'])
                if key in self.done():
                    continue
                if self.stopped():
                    self.log('STOP seen; lane ends')
                    return
                kind = step['kind']
                only = self.only()
                if only and kind not in only:   # build/lanes/<subject>/ONLY: run just these kinds, leave the rest queued
                    continue
                if kind == 'LEAD' and step['detail'].startswith('subject close'):
                    # the queue is made one course at a time, so every course ends with this line; it is the lead's
                    # step only after the lane's last course
                    if course == LANES[self.subj][-1] and not self.wait_for_lead(key, step['detail']):
                        return
                    self.mark(key)
                    continue
                if kind == 'LEAD':
                    ok, out = self.lead_step(step)
                    if ok:
                        self.commit(course, 'lead step %s %s' % (step['num'], step['detail'][:60]), {})
                        self.mark(key)
                    elif not self.wait_for_lead(key, 'lead step failed: %s\n%s' % (step['detail'], out[-2000:])):
                        return
                    continue
                if kind == 'RETOOL':
                    why = ('grade close for %s: do the retool stop in %s (browser checks, gate --record, grade report, '
                           'pass_marks.py add, spacing.py read, day_version.py grade-read, retool the kit if needed). '
                           'The next course\'s queue is generated after this, on the kit as it then stands.'
                           % (course, (self.dir / course / step['file']).as_posix()))
                    if not self.wait_for_lead(key, why):
                        return
                    continue
                if kind not in CODEX_KINDS:
                    self.log('unknown job kind %s at %s; waiting' % (kind, key))
                    if not self.wait_for_lead(key, 'unknown job kind %s' % kind):
                        return
                    continue
                if step['gate']:
                    while True:
                        code, out = self.py(*step['gate'].split()[3:])
                        if code == 0:
                            break
                        if not self.wait_for_lead(key + ':gate', 'ledger gate closed before %s %s:\n%s'
                                                  % (kind, step['detail'], out.strip()[-2500:])):
                            return
                        d = self.done()
                        if key in d:
                            break
                    if key in self.done():
                        continue
                if (kind in GATED_AFTER) and not dirty(course):
                    self.gate(course)          # a run on the clean course stores its baseline (gate.py)
                text = (self.dir / course / step['file']).read_text(encoding='utf-8')
                if course in DRAFTED and kind in MAKE_KINDS:
                    text += REVISE.format(course=course)
                note = self.dir / 'notes' / ('%s.txt' % key.replace(':', '-'))
                if note.exists():
                    text += '\n\nNote from the lead for this job (it wins over the job above):\n' + \
                            note.read_text(encoding='utf-8')
                before = dict(porcelain())
                while True:
                    while self.pause_until > time.time():
                        time.sleep(60)
                    t0 = time.time()
                    self.log('start %s %s %s %s' % (course, step['num'], kind, step['detail']))
                    job = self.codex(step, text)
                    if job['limit']:
                        self.pause_until = time.time() + LIMIT_PAUSE
                        self.usage_row(step, 'limit', t0, job, '')
                        self.log('%s: usage limit; this lane pauses 30 minutes, then the job runs again' % key)
                        continue
                    break
                result, newn = ('ok' if job['last'].strip() else 'failed'), ''
                if result == 'ok' and kind in GATED_AFTER:
                    code, out, new = self.gate(course)
                    if code == 1 and job['thread']:
                        self.log('%s: %d new gate line(s); handing them back once' % (key, len(new)))
                        job['resume']('The lead re-ran the gate for %s after your job (`python -X utf8 scripts/gate.py '
                                      '--course %s`). Fix every new failing line below that your job made, as your job '
                                      'says (never bend content to pass a gate: a rule that truly does not fit stays, '
                                      'listed as a template point). Then send your last message again, updated.\n\n%s'
                                      % (course, course, out[-7000:]), '-fix')
                        code, out, new = self.gate(course)
                    newn = len(new) if code == 1 else 0
                    if code == 2:
                        self.log('%s: gate exit 2 (no baseline for a changed course)' % key)
                    if kind in ('DAY', 'CHECKS'):
                        nums = [int(x) for x in re.findall(r'\d+', step['gate'] or '')[-2:]]
                        grade_days += (nums[1] - nums[0] + 1) if len(nums) == 2 else 0
                    grade_new += newn
                sha = self.commit(course, '%s %s %s (job %s, %s%s)' % (kind.lower(), course, step['detail'], step['num'],
                                  result, ', %d new gate lines left' % newn if newn else ''), before)
                self.usage_row(step, result, t0, job, newn)
                self.log('done %s %s %s: %s%s%s' % (course, step['num'], kind, result,
                                                    ', %d new gate lines left' % newn if newn else '',
                                                    ', commit ' + sha if sha else ''))
                self.mark(key)
                fails = 0 if result == 'ok' else fails + 1
                if fails >= MAX_FAILS:
                    if not self.wait_for_lead(key + ':fails', '%d failed jobs in a row, last %s' % (fails, key)):
                        return
                    fails = 0
                if grade_new > 10 + grade_days:
                    if not self.wait_for_lead(key + ':pileup', '%s: %d new gate lines left in %d days written; read the '
                                              'gate (`gate.py --course %s --verbose`) and fix or note before going on'
                                              % (course, grade_new, grade_days, course)):
                        return
                    grade_new = 0
        self.log('lane finished: every course of %s done' % self.subj)
        keep_awake(False)


# ---------------------------------------------------------------- shared helpers

def git(*args):
    r = subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, encoding='utf-8', errors='replace')
    return r.returncode, (r.stdout or '') + (r.stderr or '')


def porcelain():
    code, out = git('status', '--porcelain', '-uall')
    rows = []
    for ln in out.splitlines():
        if len(ln) > 3:
            p = ln[3:].split(' -> ')[-1].strip().strip('"')
            rows.append((p, ln[:2]))
    return rows


def dirty(course):
    return any(p.startswith(('docs/courses/%s/' % course, 'data/plans/%s/' % course, 'courses/%s/' % course)) for p, _ in porcelain())


def turn_held():
    try:
        return json.loads((ROOT / 'data' / 'pipeline' / 'turn.json').read_text(encoding='utf-8')).get('worker') not in (None, '')
    except (OSError, ValueError):
        return False


class gitlock:
    """One lock for every git commit in this checkout: each lane and the lead (lead-commit)."""
    def __enter__(self):
        GITLOCK.parent.mkdir(parents=True, exist_ok=True)
        while True:
            try:
                fd = os.open(GITLOCK, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(fd, ('%d %s\n' % (os.getpid(), now())).encode())
                os.close(fd)
                return self
            except FileExistsError:
                try:
                    if time.time() - GITLOCK.stat().st_mtime > 600:
                        GITLOCK.unlink()
                except FileNotFoundError:
                    pass
                time.sleep(2)

    def __exit__(self, *a):
        try:
            GITLOCK.unlink()
        except FileNotFoundError:
            pass


def push(log):
    code, out = git('push', '-q', 'origin', 'HEAD:main')
    if code:
        log('push held (the commit stays local; the next push carries it): %s' % out.strip()[:200])


